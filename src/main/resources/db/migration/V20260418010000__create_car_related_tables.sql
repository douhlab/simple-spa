IF
OBJECT_ID('CAR_FUEL_EVENT', 'U') IS NOT NULL
DROP TABLE CAR_FUEL_EVENT;

IF
OBJECT_ID('CAR_EXPENSE', 'U') IS NOT NULL
DROP TABLE CAR_EXPENSE;

IF
OBJECT_ID('CAR_SERVICE_STATION', 'U') IS NOT NULL
DROP TABLE CAR_SERVICE_STATION;

IF
OBJECT_ID('CAR', 'U') IS NOT NULL
DROP TABLE CAR;

CREATE TABLE CAR
(
    ID                      INT IDENTITY(1,1),
    USER_ID                 INT,
    NAME                    NVARCHAR(50),
    MODEL                   NVARCHAR(50),
    MODEL_YEAR              SMALLINT,
    OWNED_DATE              DATE,
    ODOMETER_WHEN_OWNED     DECIMAL(10, 2),
    PRICE_IN_USD_WHEN_OWNED DECIMAL(10, 2),
    NOTE                    NVARCHAR(255),
    CREATION_DATE           DATETIME,
    CREATED_BY              NVARCHAR(50),

    CONSTRAINT PK_CAR_ID PRIMARY KEY (ID),
    CONSTRAINT FK_CAR_USER_ID FOREIGN KEY (USER_ID) REFERENCES USERS (ID),
    CONSTRAINT CHK_MODEL_YEAR_RANGE CHECK (MODEL_YEAR BETWEEN 1900 AND 9999),
    CONSTRAINT CHK_ODOMETER_WHEN_OWNED CHECK (ODOMETER_WHEN_OWNED >= 0),
    CONSTRAINT CHK_PRICE_IN_USD_WHEN_OWNED CHECK (PRICE_IN_USD_WHEN_OWNED >= 0)
);

CREATE TABLE CAR_SERVICE_STATION
(
    ID        INT IDENTITY(1,1),
    NAME      NVARCHAR (50),
    LOCATION  NVARCHAR (50),
    TYPE_CODE TINYINT,
    NOTE      NVARCHAR (100),

    CONSTRAINT PK_CAR_SERVICE_STATION_ID PRIMARY KEY (ID),
    CONSTRAINT CHK_CAR_SERVICE_STATION_TYPE_CODE CHECK (TYPE_CODE BETWEEN 1 AND 20)
);

CREATE TABLE CAR_EXPENSE
(
    ID                 INT IDENTITY(1,1),
    CAR_ID             INT,
    TYPE_CODE          TINYINT,
    DESCRIPTION        NVARCHAR(255),
    AMOUNT_IN_USD      DECIMAL(10, 2),
    SERVICE_STATION_ID INT,
    MAIN_ODOMETER      DECIMAL(10, 2),
    DATE_HAPPENED      DATE,
    NOTE               NVARCHAR(255),
    CREATION_DATE      DATETIME,
    CREATED_BY         NVARCHAR(50),

    CONSTRAINT PK_CAR_EXPENSE_ID PRIMARY KEY (ID),
    CONSTRAINT FK_CAR_EXPENSE_CAR_ID FOREIGN KEY (CAR_ID) REFERENCES CAR (ID),
    CONSTRAINT FK_CAR_SERVICE_STATION_ID FOREIGN KEY (SERVICE_STATION_ID) REFERENCES CAR_SERVICE_STATION (ID),
    CONSTRAINT CHK_CAR_EXPENSE_TYPE_CODE CHECK (TYPE_CODE BETWEEN 1 AND 10),
    CONSTRAINT CHK_MAIN_ODOMETER CHECK (MAIN_ODOMETER >= 0),
    CONSTRAINT CHK_AMOUNT_IN_USD CHECK (AMOUNT_IN_USD >= 0)
);

CREATE TABLE CAR_FUEL_EVENT
(
    ID                     INT IDENTITY(1,1),
    CAR_EXPENSE_ID         INT,
    REFILL_AMOUNT_IN_LITER DECIMAL(10, 2),
    MILEAGE_TRAVERSED      DECIMAL(10, 2),
    FUEL_TYPE_CODE         TINYINT,

    CONSTRAINT PK_CAR_FUEL_EVENT_ID PRIMARY KEY (ID),
    CONSTRAINT FK_CAR_FUEL_EVENT_EXPENSE_ID FOREIGN KEY (CAR_EXPENSE_ID) REFERENCES CAR_EXPENSE (ID),
    CONSTRAINT CHK_REFILL_AMOUNT_IN_LITER CHECK (REFILL_AMOUNT_IN_LITER > 0),
    CONSTRAINT CHK_MILEAGE_TRAVERSED CHECK (MILEAGE_TRAVERSED > 0),
    CONSTRAINT CHK_FUEL_TYPE_CODE CHECK (FUEL_TYPE_CODE IN (1, 2, 3, 4, 5))
);
