CREATE TABLE USER_ASSETS (
    ID INT IDENTITY(1,1),
    USER_ID INT NOT NULL,
    EUR_AMOUNT DECIMAL(18, 4) NOT NULL,
    CHF_AMOUNT DECIMAL(18, 4) NOT NULL,
    AUD_AMOUNT DECIMAL(18, 4) NOT NULL,
    CAD_AMOUNT DECIMAL(18, 4) NOT NULL,
    GOLD_OUNCE DECIMAL(18, 4) NOT NULL,
    SILVER_OUNCE DECIMAL(18, 4) NOT NULL,
    USD_AMOUNT DECIMAL(18, 4) NOT NULL,
    USD_FNB_AMOUNT DECIMAL(18, 4) NOT NULL,
    CRYPTO_BTC_AMOUNT DECIMAL(18, 8) NOT NULL,
    GUN_AMOUNT_USD DECIMAL(18, 4) NOT NULL,
    CREATION_DATE DATETIME NOT NULL,
    CREATED_BY NVARCHAR(255) NOT NULL,

    CONSTRAINT PK_USER_ASSETS PRIMARY KEY (ID),
    CONSTRAINT UK_USER_ASSETS_USER_ID UNIQUE (USER_ID),
    CONSTRAINT FK_USER_ASSETS_USER_ID FOREIGN KEY (USER_ID) REFERENCES USERS(ID)
);
